# Пиксельные иконки древа талантов: ASCII-силуэты 14×14 (материал = буква).
# Строчная буква — автотон (верх/лево светлее, низ/право темнее), заглавная — тёмный тон,
# «.» — пусто. Контур (#00303B, как у иконок Paper UI) дорисовывается автоматически.
ICONS = {}

def icon(name, art):
    rows = [r for r in art.strip('\n').split('\n')]
    rows = [r.strip() for r in rows]
    w = max(len(r) for r in rows)
    ICONS[name] = [r.ljust(w, '.') for r in rows]

